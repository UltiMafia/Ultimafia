"""Vendor only mapped free Pixelarticons from a pinned upstream revision.

Downloads original SVG/license bytes as data; does not install or execute an
upstream package. Validates SVG structure, records hashes, and generates the
small path-data module consumed by UiIcon. The site wordmark is never an input.
"""
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import urllib.request
import xml.etree.ElementTree as ET

REVISION = 'c9ecc2da61afde85dbe539025e3d931c6152ad75'
REPOSITORY = 'https://github.com/halfmage/pixelarticons'
BASE = f'https://raw.githubusercontent.com/halfmage/pixelarticons/{REVISION}/'
FRONTEND = Path(__file__).resolve().parents[1]
DESTINATION = FRONTEND / 'src/components/ui/pixelarticons'
mapping = json.loads((DESTINATION / 'source-map.json').read_text())

def download(relative):
    request = urllib.request.Request(BASE + relative, headers={'User-Agent': 'UltiMafia-icon-import'})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()

def icon(name):
    assert name.replace('-', '').isalnum()
    contents = download(f'svg/{name}.svg')
    root = ET.fromstring(contents)
    assert root.tag == '{http://www.w3.org/2000/svg}svg', name
    assert root.attrib.get('viewBox') == '0 0 24 24', name
    paths = []
    for child in root:
        assert child.tag == '{http://www.w3.org/2000/svg}path', (name, child.tag)
        assert set(child.attrib) <= {'d', 'fill', 'fill-rule', 'clip-rule'}, (name, child.attrib)
        assert child.attrib.get('fill', 'currentColor') in ['currentColor', '#000', '#000000', 'black'], name
        path = {'d': child.attrib['d']}
        for source, target in [('fill-rule', 'fillRule'), ('clip-rule', 'clipRule')]:
            if source in child.attrib:
                assert child.attrib[source] in ['evenodd', 'nonzero']
                path[target] = child.attrib[source]
        paths.append(path)
    assert paths, name
    return name, contents, paths

def write_asset(destination, contents):
    if destination.exists() and destination.read_bytes() != contents:
        raise RuntimeError(f'Refusing to overwrite changed vendored asset: {destination}')
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_bytes(contents)

license_bytes = download('LICENSE')
assert b'MIT License' in license_bytes and b'Gerrit Halfmann' in license_bytes
with ThreadPoolExecutor(max_workers=6) as executor:
    icons = list(executor.map(icon, sorted(set(mapping.values()))))

data = {}
records = []
for name, contents, paths in icons:
    write_asset(DESTINATION / (name + '.svg'), contents)
    data[name] = paths
    records.append({'name': name, 'file': name + '.svg', 'sha256': hashlib.sha256(contents).hexdigest(), 'source': BASE + 'svg/' + name + '.svg'})
write_asset(DESTINATION / 'LICENSE.txt', license_bytes)
write_asset(FRONTEND / 'public/licenses/pixelarticons.txt', license_bytes)
(DESTINATION / 'SOURCE.json').write_text(json.dumps({'library': 'Pixelarticons (free set)', 'author': 'Gerrit Halfmann', 'repository': REPOSITORY, 'revision': REVISION, 'license': 'MIT', 'licenseSha256': hashlib.sha256(license_bytes).hexdigest(), 'modifications': 'None to SVG artwork. Path attributes extracted into icons.js for local React rendering.', 'files': records}, indent=2) + '\n')
(DESTINATION / 'icons.js').write_text('/*! Pixelarticons, copyright (c) 2019 Gerrit Halfmann. MIT. See LICENSE.txt and /licenses/pixelarticons.txt. */\n// Generated by test/import-pixelarticons.py from original SVGs; do not hand-edit.\nexport const pixelarticonSources = ' + json.dumps(mapping, indent=2) + ';\nexport default ' + json.dumps(data, indent=2) + ';\n')
print(f'Imported {len(icons)} unmodified MIT-licensed SVGs for {len(mapping)} semantic names, plus license and provenance.')
